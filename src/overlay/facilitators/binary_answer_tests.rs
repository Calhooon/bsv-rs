#![cfg(test)]
//! #735's fold: the generated-bytes bound and the per-txid cache of
//! `atomic_outputs`, on a BEEF this crate's writer builds (the door test,
//! against the reference's recorded bytes, is
//! `tests/identity_evidence_hint_735.rs`).
#![allow(clippy::unwrap_used)]

use super::*;
use crate::script::{LockingScript, UnlockingScript};
use crate::transaction::{
    MerklePath, MerklePathLeaf, Transaction, TransactionInput, TransactionOutput,
};

/// A transaction spending `<byte>`x32:0, proven by a block of its own.
fn proven(beef: &mut Beef, byte: &str, height: u32) -> String {
    let mut input = TransactionInput::new(byte.repeat(32), 0);
    input.set_unlocking_script(UnlockingScript::from_hex("").unwrap());
    let mut tx = Transaction::new();
    tx.add_input(input).unwrap();
    tx.add_output(TransactionOutput::new(
        1,
        LockingScript::from_hex("51").unwrap(),
    ))
    .unwrap();
    let path = MerklePath::new(height, vec![vec![MerklePathLeaf::new_txid(0, tx.id())]]).unwrap();
    let index = beef.merge_bump(path);
    beef.merge_raw_tx(tx.to_binary(), Some(index))
        .expect("the bytes are one transaction");
    tx.id()
}

/// Two proven transactions in one BEEF: its bytes, the txids and each
/// txid's Atomic BEEF length.
fn two() -> (Vec<u8>, String, String, usize, usize) {
    let mut beef = Beef::new();
    let a = proven(&mut beef, "11", 900);
    let b = proven(&mut beef, "22", 901);
    let bytes = beef.to_binary().expect("the BEEF is writable");
    let la = beef.to_binary_atomic(&a).unwrap().len();
    let lb = beef.to_binary_atomic(&b).unwrap().len();
    (bytes, a, b, la, lb)
}

fn words(result: Result<Vec<OutputListItem>>) -> String {
    match result {
        Err(Error::OverlayError(words)) => words,
        other => panic!("not an overlay error: {other:?}"),
    }
}

/// The reference's figure (`LookupResolver.ts:257`).
#[test]
fn the_bound_is_the_references_64_mib_735() {
    assert_eq!(MAX_AGGREGATED_BEEF_BYTES, 64 * 1024 * 1024);
}

/// Generated bytes at the bound are read, one past it refused in the
/// reference's words (`:924-927`, `>`), at the outpoint that crosses.
#[test]
fn generated_bytes_past_the_bound_refuse_the_answer_in_the_references_words_735() {
    let (bytes, a, b, la, lb) = two();
    let outpoints = || vec![(a.clone(), 0, None), (b.clone(), 0, None)];
    let read = atomic_outputs_within(outpoints(), &bytes, la + lb, usize::MAX).unwrap();
    assert_eq!(read.len(), 2);
    assert_eq!(
        words(atomic_outputs_within(
            outpoints(),
            &bytes,
            la + lb - 1,
            usize::MAX
        )),
        "Aggregated overlay BEEF exceeds the maximum permitted size."
    );
}

/// A txid named by several outpoints is generated and counted once
/// (`beefByTxid`, `:919-929`): three outpoints of one transaction pass a
/// bound of its one Atomic BEEF, each output carrying the same bytes.
#[test]
fn a_txid_named_twice_is_generated_and_counted_once_735() {
    let (bytes, a, _, la, _) = two();
    let outpoints = vec![
        (a.clone(), 0, None),
        (a.clone(), 0, Some(vec![7])),
        (a.clone(), 0, None),
    ];
    let read = atomic_outputs_within(outpoints, &bytes, la, usize::MAX).unwrap();
    assert_eq!(read.len(), 3);
    assert!(read.iter().all(|o| o.beef == read[0].beef));
    assert!(read.iter().all(|o| o.txid.as_deref() == Some(a.as_str())));
    assert_eq!(read[1].context, Some(vec![7]));
}

/// The extracted-bytes response bound (#775, `:929-932`): each outpoint's
/// Atomic BEEF and context counted, a repeated txid counted again (unlike
/// the generated bytes), the total at the bound read and one past it
/// refused in the neutral class, never the whole BEEF per outpoint.
#[test]
fn extracted_bytes_count_each_outpoints_atomic_beef_and_context_775() {
    let (bytes, a, b, la, lb) = two();
    let outpoints = || {
        vec![
            (a.clone(), 0, Some(vec![1, 2, 3])),
            (a.clone(), 1, None),
            (b.clone(), 0, None),
        ]
    };
    let total = la + 3 + la + lb;
    assert!(total < 3 * bytes.len() + 3);
    let read = atomic_outputs_within(outpoints(), &bytes, usize::MAX, total).unwrap();
    assert_eq!(read.len(), 3);
    assert_eq!(
        atomic_outputs_within(outpoints(), &bytes, usize::MAX, total - 1).unwrap_err(),
        Error::OverlayResourceLimit("maxResponseBytes".into())
    );
}
