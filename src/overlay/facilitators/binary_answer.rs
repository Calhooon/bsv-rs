//! A binary aggregated answer's outputs (#735's fold), beside the
//! facilitator that reads the answer: `facilitators.rs` stays under the
//! ratchet's bounds.
//!
//! The reference parses the answer's BEEF once and gives every output the
//! Atomic BEEF of its own outpoint's txid, one per distinct txid
//! (`ts-stack@edf6e03` `packages/sdk/src/overlay-tools/LookupResolver.ts:905-936`,
//! `extractAtomicOutputs`: `beefObj.toBinaryAtomic(x.txid)` memoized in
//! `beefByTxid`), so a consumer reading an output's BEEF reads that
//! outpoint's own subject: the identity evidence check selects it and its
//! `txid` hint agrees (`TransactionEvidence.ts:110-128`), and the resolver's
//! dedup key, the BEEF's txid and the index, tells apart two outpoints of
//! different transactions that share an index. Until the fold every output
//! here carried the whole BEEF, whose subject is its last transaction.

use crate::overlay::lookup_limits::resource_limit;
use crate::overlay::types::OutputListItem;
use crate::transaction::Beef;
use crate::{Error, Result};
use std::collections::HashMap;

/// The reference's bound on the Atomic BEEF bytes generated for one binary
/// aggregated answer, each distinct txid's counted once
/// (`LookupResolver.ts:257`, `MAX_AGGREGATED_BEEF_BYTES`, checked at
/// `:924-927`): 64 MiB.
pub(super) const MAX_AGGREGATED_BEEF_BYTES: usize = 64 * 1024 * 1024;

/// One outpoint of a binary aggregated answer: the txid as its 32 bytes'
/// hex, the output index and the context.
pub(super) type Outpoint = (String, u32, Option<Vec<u8>>);

/// The answer's outputs, each carrying the Atomic BEEF of its outpoint's
/// txid (`extractAtomicOutputs`, `:905-936`) and that txid as its hint
/// (#735).
///
/// Refused, each an `Err` for the whole answer as the reference throws for
/// it: a BEEF that does not parse (`Beef.fromBinary`, `:900`; an answer of no
/// outpoint and no BEEF among them), an outpoint whose txid the BEEF does
/// not hold (`toBinaryAtomic`'s `<txid> does not exist in this Beef`), and
/// generated bytes past [`MAX_AGGREGATED_BEEF_BYTES`] in the reference's
/// words. Those are plain `Error`s in the reference (the 64 MiB refusal a
/// resource bound thrown as one, `:926`, not its
/// `LookupResourceLimitError`), so its tracker records them against the host
/// (`throwTrackedLookupFailure`, `:2408-2419`), as every `Err` of this
/// facilitator but [`Error::OverlayResourceLimit`] is recorded here. The
/// one reputation-neutral refusal of this function is the extracted-bytes
/// response bound (`:929-932`, #775): each outpoint's Atomic BEEF and
/// context bytes summed over the outputs, past `max_response_bytes`
/// [`Error::OverlayResourceLimit`] (`maxResponseBytes`), checked after the
/// 64 MiB bound at the outpoint that crosses it, as the reference orders
/// them.
pub(super) fn atomic_outputs(
    outpoints: Vec<Outpoint>,
    beef: &[u8],
    max_response_bytes: usize,
) -> Result<Vec<OutputListItem>> {
    atomic_outputs_within(
        outpoints,
        beef,
        MAX_AGGREGATED_BEEF_BYTES,
        max_response_bytes,
    )
}

/// [`atomic_outputs`] under a caller's generated-bytes bound (the unit
/// tests' seam: 64 MiB of BEEF is not built to reach the refusal).
fn atomic_outputs_within(
    outpoints: Vec<Outpoint>,
    beef: &[u8],
    max_generated: usize,
    max_response_bytes: usize,
) -> Result<Vec<OutputListItem>> {
    let mut beef = Beef::from_binary(beef)
        .map_err(|e| Error::OverlayError(format!("Failed to parse BEEF: {e}")))?;
    let mut by_txid: HashMap<String, Vec<u8>> = HashMap::new();
    let mut generated = 0usize;
    let mut extracted = 0usize;
    let mut outputs = Vec::with_capacity(outpoints.len());
    for (txid, output_index, context) in outpoints {
        let atomic = match by_txid.get(&txid) {
            Some(atomic) => atomic.clone(),
            None => {
                let atomic = beef
                    .to_binary_atomic(&txid)
                    .map_err(|e| Error::OverlayError(format!("Failed to extract BEEF: {e}")))?;
                generated = generated.saturating_add(atomic.len());
                if generated > max_generated {
                    return Err(Error::OverlayError(
                        "Aggregated overlay BEEF exceeds the maximum permitted size.".into(),
                    ));
                }
                by_txid.insert(txid.clone(), atomic.clone());
                atomic
            }
        };
        // `extractedBytes += beefBytes.length + (x.context?.length ?? 0)`,
        // the neutral class (`:929-932`, #775)
        extracted = extracted
            .saturating_add(atomic.len())
            .saturating_add(context.as_ref().map_or(0, Vec::len));
        if extracted > max_response_bytes {
            return Err(resource_limit("maxResponseBytes"));
        }
        outputs.push(OutputListItem {
            beef: atomic,
            output_index,
            context,
            txid: Some(txid),
        });
    }
    Ok(outputs)
}

